import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// Build tools/generate-display-font-atlas.c first; pass its executable path.
const executable = process.argv[2]
if (!executable) throw new Error('Usage: node tools/regenerate-display-fonts.mjs GENERATOR_PATH')

for (const [name, file, size, copyright] of [
  ['standard', 'PixelmixRegular-z07w.ttf', 8, 'pixelmix: Copyright pixelmix 2010; CC BY-SA 3.0.'],
  ['tiny', 'tom-thumb.ttf', 6, 'Tom Thumb: Copyright Lord Nightmare 2019; CC BY 3.0.'],
]) {
  const data = execFileSync(executable, [
    fileURLToPath(new URL(`./fonts/${file}`, import.meta.url)),
    String(size), 'mono', `${name.toUpperCase()}_FONT_ATLAS`,
  ], { encoding: 'utf8' })
  const header = `// Generated by tools/generate-display-font-atlas.c via tools/regenerate-display-fonts.mjs.
// Source: tools/fonts/${file}. Do not edit by hand.
// ${copyright}
// Simulator font approximation; hardware glyph parity is unverified.

import type { DistingFontAtlas } from './display-font'

`
  writeFileSync(new URL(`../src/disting/emulation/${name}-font-atlas.generated.ts`, import.meta.url), header + data)
}
